using System;

namespace calculadora;

public class metodo
{
    public static double metodo1(double numero1, double numero2){
        return Math.Pow(numero1, numero2);}
    public static double metodo2(double numero1){
        return Math.Sqrt(numero1);}
    public static double metodo3(double numero1){
        return Math.Sin(numero1);}
    public static double metodo4(double numero1){
        return Math.Cos(numero1);}
    public static double metodo5(double numero1){
        return Math.Tan(numero1);}
    public static double metodo6(double numero1){
        return Math.Round(numero1);}
    public static double metodo7(double numero1){
        return Math.Abs(numero1);}
    public static double metodo8(double numero1){
        return Math.Log(numero1);}
}    
  
